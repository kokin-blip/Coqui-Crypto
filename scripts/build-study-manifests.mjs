import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, relative } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import ts from 'typescript';

export const STUDY_ENTRIES = {
  'wider-breakout-v1': 'apps/desktop/src/main/breakout-runtime.ts',
  'wider-range-rotation-v1': 'apps/desktop/src/main/range-rotation-runtime.ts',
  'paper-market-selector-v1': 'apps/desktop/src/main/market-selector-runtime.ts',
  'trendvol-hourly-execution-v1': 'packages/services/src/paper/parallel-hourly-shadow.ts',
  'trendvol-execution-remediation-v1': 'packages/services/src/paper/execution-remediation-shadow.ts',
};
const hash = (value) => createHash('sha256').update(value).digest('hex');
/** Parse imports/exports with the compiler, including side effects and literal dynamic imports. */
export function dependencyManifest(root, entry, read = readFileSync) {
  const visited = new Map();
  const visit = (file) => {
    const key = relative(root, file).replaceAll('\\', '/');
    if (visited.has(key)) return;
    const content = String(read(file, 'utf8'));
    visited.set(key, hash(content));
    const source = ts.createSourceFile(file, content, ts.ScriptTarget.Latest, true);
    const dependencies = [];
    const walk = (node) => {
      if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier && ts.isStringLiteral(node.moduleSpecifier))
        dependencies.push(node.moduleSpecifier.text);
      if (ts.isCallExpression(node) && node.expression.kind === ts.SyntaxKind.ImportKeyword) {
        if (!node.arguments[0] || !ts.isStringLiteral(node.arguments[0])) throw new Error(`nonliteral_study_import:${key}`);
        dependencies.push(node.arguments[0].text);
      }
      ts.forEachChild(node, walk);
    };
    walk(source);
    for (const dependency of dependencies) {
      // Manifest access is evidence plumbing, not a dependency of the strategy it records.
      if (/study-manifests\.json$/u.test(dependency) || /study-manifests\.generated\.js$/u.test(dependency)) continue;
      let target;
      if (dependency.startsWith('@coqui/')) target = resolve(root, 'packages', dependency.slice(7), 'src/index.ts');
      else if (dependency.startsWith('.')) target = resolve(dirname(file), dependency.replace(/\.js$/u, '.ts'));
      else continue;
      if (!existsSync(target)) throw new Error(`unresolved_study_dependency:${key}:${dependency}`);
      visit(target);
    }
  };
  visit(resolve(root, entry));
  const members = [...visited].sort(([a],[b]) => a.localeCompare(b));
  // Package versions and build settings affect behavior even when source text does not change.
  for (const file of ['pnpm-lock.yaml','tsconfig.base.json','scripts/build-study-manifests.mjs']) members.push([file, hash(String(read(resolve(root,file),'utf8')))]);
  return { version: 1, entry, members, hash: hash(JSON.stringify(members)) };
}
export function buildStudyManifests(root) {
  return Object.fromEntries(Object.entries(STUDY_ENTRIES).map(([candidate, entry]) => [candidate, dependencyManifest(root, entry)]));
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const manifests = buildStudyManifests(resolve('.'));
  writeFileSync(resolve('docs/studies/behavior-manifests-v1.json'), JSON.stringify(manifests, null, 2)+'\n');
  writeFileSync(resolve('packages/core/src/research/study-manifests.generated.ts'), '// Generated by scripts/build-study-manifests.mjs.\nexport const STUDY_BEHAVIOR_HASHES: Readonly<Record<string,string>> = '+JSON.stringify(Object.fromEntries(Object.entries(manifests).map(([id,m])=>[id,m.hash])), null, 2)+';\n');
}
